// Helper: get songs for album
export function getSongsForAlbum(albumId: string): Song[] {
  const album = getAlbumById(albumId);
  if (!album) return [];
  return album.songs.map(getSongById).filter(Boolean) as Song[];
}

// Helper: get songs for playlist
export function getSongsForPlaylist(playlistId: string): Song[] {
  const playlist = mockPlaylists.find((p) => p.id === playlistId);
  if (!playlist) return [];
  return playlist.songs.map(getSongById).filter(Boolean) as Song[];
}
